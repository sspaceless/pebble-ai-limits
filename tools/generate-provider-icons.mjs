import { readFile, writeFile } from 'node:fs/promises';
import { format, resolveConfig } from 'prettier';

const icons = {
  codex: 'codex-mark.svg',
  gemini: 'gemini-mark.svg',
  claude: 'claude-mark.svg',
  custom: 'custom-mark.svg'
};

const entries = await Promise.all(
  Object.entries(icons).map(async ([name, file]) => {
    const svg = (await readFile(new URL(`../assets/${file}`, import.meta.url), 'utf8')).trim();
    return `  ${name}: ${JSON.stringify(svg)}`;
  })
);

const output = `// Generated by tools/generate-provider-icons.mjs from assets/*-mark.svg. Do not edit by hand.
var SVG = {
${entries.join(',\n')}
};

function providerIcon(id) {
  var name = id === 'gemini' || id === 'gemini-api' ? 'gemini' :
    id === 'claude' || id === 'claude-api' ? 'claude' :
    id === 'custom' ? 'custom' : 'codex';
  var className = name === 'custom' ? 'provider-symbol custom-symbol' :
    name === 'codex' ? 'provider-symbol codex-symbol' : 'provider-symbol';
  return '<span class="' + className + '">' + SVG[name] + '</span>';
}

module.exports = { SVG: SVG, providerIcon: providerIcon };
`;

const target = new URL('../src/pkjs/provider-icons.js', import.meta.url);
await writeFile(
  target,
  await format(output, { ...(await resolveConfig(target)), parser: 'babel' })
);
