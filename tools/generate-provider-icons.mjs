import { readFile, writeFile } from 'node:fs/promises';
import { format, resolveConfig } from 'prettier';

const icons = {
  codex: 'codex-mark.svg',
  gemini: 'gemini-mark.svg',
  claude: 'claude-mark.svg',
  custom: 'custom-mark.svg'
};

const entries = await Promise.all(
  Object.entries(icons).map(async ([name, file]) => {
    const svg = (await readFile(new URL(`../assets/${file}`, import.meta.url), 'utf8')).trim();

    return `  ${name}: ${JSON.stringify(svg)}`;
  })
);

const output = `// Generated by tools/generate-provider-icons.mjs from assets/*-mark.svg. Do not edit by hand.
module.exports = {
${entries.join(',\n')}
};
`;

const target = new URL('../src/pkjs/resources/provider-svg.js', import.meta.url);

await writeFile(
  target,
  await format(output, { ...(await resolveConfig(target)), parser: 'babel' })
);
